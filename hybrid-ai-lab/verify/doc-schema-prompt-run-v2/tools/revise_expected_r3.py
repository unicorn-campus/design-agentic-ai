def main() -> None:
    src, bak = BASE / "regulation" / "expected_answers.json", BASE / "regulation" / "expected_answers.r2.json"
    if not bak.exists():
        shutil.copy(src, bak)
    units = {u["id"]: u for u in load_units()}
    e = load_json("regulation/expected_answers.r2.json")
    missing, changes = [], []
    for cid, a in e["answers"].items():
        no = cid.split(":", 1)[1]
        text = units[cid]["text"].replace("\n", " ")
        for q, val in zip(("R2", "R3", "R4"), ANS[no]):
            if val != X:
                missing += [(no, q, s) for s in val if s.replace("\n", " ") not in text]
            new = X if val == X else " / ".join(val)
            if new != a[q]["answer"]:
                changes.append({"chunk_id": cid, "q": q, "before": a[q]["answer"], "after": new})
                a[q] = {"answer": new, "location": "원문" if new != X else "", "source": "3라운드 사람 판단(나3)"}
    if missing:
        raise SystemExit(f"원문에 없는 문장: {missing}")
    e["r3_changes"] = changes
    save_json("regulation/expected_answers.json", e)
    has = {q: sum(1 for a in e["answers"].values() if a[q]["answer"] != X) for q in ("R2", "R3", "R4")}
    print("고친 칸", len(changes), "| 답 있음", has)


if __name__ == "__main__":
    main()
